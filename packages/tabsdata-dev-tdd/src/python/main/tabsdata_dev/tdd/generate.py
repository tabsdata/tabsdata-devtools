"""Generating toolset packages and the catalog. Standard library only."""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
import sys
import tomllib

from . import catalog as catalog_mod
from . import discover as discover_mod
from . import paths
from . import version as version_mod

TOOLSET_PREFIX = discover_mod.TOOLSET_PREFIX
DEPS_PREFIX = discover_mod.DEPS_PREFIX

COPYRIGHT = "Copyright 2026 Tabsdata Inc."
HEADER = (
    f"#\n# {COPYRIGHT}\n#\n\n# GENERATED by `cargo make gen` -- do not edit by hand.\n"
)


def _fingerprint(payload: dict) -> str:
    blob = json.dumps(payload, sort_keys=True).encode()
    return hashlib.sha256(blob).hexdigest()[:16]


def _toolset_pyproject(
    name: str, version: str, tool_dists: list[str], commons: list[str]
) -> str:
    bundle = DEPS_PREFIX + name
    members = [bundle] + sorted(tool_dists)
    lines = [
        HEADER,
        "[project]",
        f'name = "{TOOLSET_PREFIX}{name}"',
        # A toolset has no build backend, so it cannot read VERSION itself the
        # way the other packages do; the generator writes the value in.
        f'version = "{version}"',
        f'description = "toolset {name}: materialized environment"',
        'requires-python = ">=3.11"',
        "dependencies = [",
    ]
    lines += [f'    "{m}",' for m in members]
    lines += [
        "]",
        "",
        "[tool.uv.sources]",
    ]
    for m in members + commons:
        lines.append(f'{m} = {{ path = "../{m}", editable = true }}')
    lines.append("")
    return "\n".join(lines)


def generate(root: pathlib.Path) -> dict:
    """Emit toolset-*/pyproject.toml and the catalog. Returns the catalog."""
    found = discover_mod.discover(root)
    commons = discover_mod.common_packages(root)
    version = (root / version_mod.VERSION_NAME).read_text().strip()

    for name, dists in sorted(found["toolsets"].items()):
        target = root / "packages" / (TOOLSET_PREFIX + name)
        (target / "src" / "python" / "main").mkdir(parents=True, exist_ok=True)
        (target / "pyproject.toml").write_text(
            _toolset_pyproject(name, version, dists, commons)
        )

    for warning in _check_common_floor(root, found):
        print(f"  warning: {warning}")

    # Every first-party distribution belonging to each toolset. Wheels-mode
    # installs need this explicitly: they install with --no-deps so the
    # exported lock stays authoritative, which also blocks first-party
    # dependency resolution.
    members = {
        name: sorted({DEPS_PREFIX + name, *dists, *commons})
        for name, dists in found["toolsets"].items()
    }

    result = {
        "schema": 1,
        "fingerprint": _fingerprint(
            {"tools": found["tools"], "members": members, "shell": found["shell"]}
        ),
        "toolsets": sorted(found["toolsets"]),
        "members": members,
        "tools": found["tools"],
        # Shell commands are not dispatched from the catalog -- tdd-source.sh
        # has its own registry -- but their reqs live here so `tdd --reqs` can
        # report both halves on a machine where nothing is sourced yet.
        "shell": found["shell"],
    }
    catalog_mod.write(catalog_mod.shipped_path(), result)
    return result


def _check_common_floor(root: pathlib.Path, found: dict) -> list[str]:
    """Report shared dependencies that resolved differently across toolsets.

    Divergence is legitimate when a deps-* bundle pins it deliberately -- that
    is the whole reason toolsets exist. What this catches is accidental drift:
    a common-* range that resolved to different versions because the toolset
    locks were generated at different times rather than in one pass.
    `tdd-install --relock` puts them back in step.
    """
    pinned: dict[str, set[str]] = {}
    resolved: dict[str, dict[str, str]] = {}

    for toolset in found["toolsets"]:
        bundle = root / "packages" / (DEPS_PREFIX + toolset) / "pyproject.toml"
        if bundle.is_file():
            deps = tomllib.loads(bundle.read_text())["project"].get("dependencies", [])
            pinned[toolset] = {
                re.split(r"[<>=!~\[]", dep, maxsplit=1)[0].strip().lower()
                for dep in deps
            }

        lock = root / "packages" / (TOOLSET_PREFIX + toolset) / "uv.lock"
        if not lock.is_file():
            continue
        for package in tomllib.loads(lock.read_text()).get("package", []):
            name = package["name"].lower()
            if name.startswith("tabsdata-dev-"):
                continue
            resolved.setdefault(name, {})[toolset] = package.get("version", "?")

    warnings = []
    for name, by_toolset in sorted(resolved.items()):
        if len(by_toolset) < 2 or len(set(by_toolset.values())) < 2:
            continue
        if any(name in pinned.get(ts, set()) for ts in by_toolset):
            continue  # a deps-* bundle asked for this difference
        spread = ", ".join(f"{ts}={v}" for ts, v in sorted(by_toolset.items()))
        warnings.append(
            f"{name} drifted across toolsets ({spread}); run `tdd-install --relock`"
        )
    return warnings


def main() -> int:
    """`python -m tabsdata_dev.tdd.generate`, what `cargo make gen` runs."""
    root = paths.repo_root()
    if root is None:
        print("tdd: no source repo; nothing to generate", file=sys.stderr)
        return 2
    catalog = generate(root)
    print(
        f"  generated {len(catalog['tools'])} tools "
        f"across {len(catalog['toolsets'])} toolsets"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
